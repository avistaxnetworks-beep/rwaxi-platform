// Exports compiled ABIs (and the factory bytecode) as typed `as const` modules
// into packages/blockchain-sdk so viem can infer function/event types.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const artifacts = path.resolve(here, "../artifacts/src");
const outDir = path.resolve(here, "../../packages/blockchain-sdk/src/abi");
const CONTRACTS = ["RwaxiTenantFactory", "RwaxiComplianceRegistry", "RwaxiPropertyToken"];
const WITH_BYTECODE = new Set(["RwaxiTenantFactory"]);

fs.mkdirSync(outDir, { recursive: true });
const index = [];
for (const name of CONTRACTS) {
  const file = path.join(artifacts, `${name}.sol`, `${name}.json`);
  const art = JSON.parse(fs.readFileSync(file, "utf8"));
  const lower = name[0].toLowerCase() + name.slice(1);
  let src = `// Generated by contracts/scripts/export-abis.mjs — do not edit.\n`;
  src += `export const ${lower}Abi = ${JSON.stringify(art.abi, null, 2)} as const;\n`;
  if (WITH_BYTECODE.has(name)) src += `\nexport const ${lower}Bytecode = "${art.bytecode}" as const;\n`;
  fs.writeFileSync(path.join(outDir, `${name}.ts`), src);
  index.push(`export * from "./${name}";`);
  console.log(`abi  ${name} (${(art.deployedBytecode.length - 2) / 2} bytes deployed)`);
}
fs.writeFileSync(path.join(outDir, "index.ts"), index.join("\n") + "\n");
